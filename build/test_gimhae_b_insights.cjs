const assert=require('node:assert/strict');
const fs=require('node:fs');
const vm=require('node:vm');
const path=require('node:path');
const root=path.join(__dirname,'..');
const I=require('../data/gimhae-b-insights.js');
const html=fs.readFileSync(path.join(root,'gimhae-wondosim.html'),'utf8');
const D=JSON.parse(html.match(/<script id="dat" type="application\/json">(.*?)<\/script>/s)[1]);
const B=JSON.parse(fs.readFileSync(path.join(root,'data/gimhae-b171.json')));
const raw=JSON.stringify(D);
const classify=vm.runInNewContext(html.slice(html.indexOf('const RESPU='),html.indexOf('D.bld.features.forEach(f=>{f.properties.cl=classify'))+'\nclassify;');
const edges=new Set(B.edgeBuildingIndices);
const buildings=B.buildingIndices.map(i=>({...D.bld.features[i],properties:{...D.bld.features[i].properties,cl:classify(D.bld.features[i].properties),bidx:i,inside:true,edge:edges.has(i)}}));
const stores=B.storeIndices.map(i=>({...D.store[i],sid:i}));
const a=I.summarize(buildings,stores);
assert.equal(a.total,651);assert.equal(a.known,551);assert.equal(a.old20,511);assert.equal(a.oldPct,92.7);
assert.deepEqual(a.counts,{all:651,candidate:130,old40:351,unknown:100,edge:176});
assert.equal(a.foodRetail,285);assert.equal(a.foodRetailPct,70.7);
assert.equal(a.residential,263);assert.equal(a.neighborhood,209);
assert.equal(a.industries.reduce((n,[,v])=>n+v,0),403);
assert.equal(a.candidateEdge,buildings.filter(f=>f.properties.edge&&f.properties.cl==='shop').length);
for(const [group,n] of Object.entries(a.counts))assert.equal(I.filterBuildings(buildings,{group}).length,n);
assert.equal(I.filterBuildings(buildings,{group:'edge',candidate:true}).length,a.candidateEdge);
assert.equal(I.filterBuildings(buildings,{query:'가락로  67'}).some(f=>f.properties.rn==='가락로'&&f.properties.bn==='67'),true);
assert.equal(I.filterBuildings(buildings,{query:'존재하지않는검색어'}).length,0);
assert.equal(I.filterStores(stores,{industry:'음식'}).length,135);
assert.equal(I.filterStores(stores,{industry:'소매'}).length,150);
assert.equal(I.filterStores(stores,{industry:'소매',query:'플럼버'}).length,0);
assert.equal(I.filterStores(stores,{query:'플럼버'}).length,1);
assert.equal(I.filterStores(stores,{query:'카페'}).every(p=>[p.nm,p.rd,p.ad,p.L,p.M,p.S].join(' ').includes('카페')),true);
assert.equal(I.summarize([],[]).oldPct,0);
assert.equal(I.filterBuildings([{properties:{yr:0}},{properties:{yr:1986}},{properties:{yr:1987}}],{group:'old40'}).length,1);
assert.equal(I.filterBuildings([{properties:{edge:true,inside:false}},{properties:{edge:true,inside:true}}],{group:'edge'}).length,1);
assert.equal(JSON.stringify(D),raw,'source data must remain immutable');
assert.equal(require('node:crypto').createHash('sha256').update(fs.readFileSync(path.join(root,'data/gimhae-b171.json'))).digest('hex'),'3ddffde8104777e2647143c342138b22ba560ae4e76f5bdf00c4db3b86f9190a','accepted boundary unchanged');
